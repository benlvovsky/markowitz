"""Invariants of the COMMITTED backtest results in `pipeline/results/`.

Separate from `test_backtest_invariants.py`, which is deliberately synthetic because the properties
it checks (a lookahead, a hole in a period, a momentum skip) are ones no file on disk can
distinguish. These are the other kind: things a *written file* can be wrong about while every
number in it is individually plausible. Nothing else in either suite opens these files -- they are
generated by hand, committed as evidence, and never rebuilt by CI -- so this is also the only place
a stale one produced by an older pipeline would be noticed.

WHY THIS FILE EXISTS, precisely, because the reason is narrower than it looks. Every printer looks
its benchmark row up by name, building the key from the block's own `benchmark` field, so the field
is a JOIN KEY and not a label. `main` recorded the UNIVERSE's benchmark in the rolling block while
passing the `--benchmark` OVERRIDE to `run_rolling`. On the shipped ETF universe those are the same
symbol and the mistake is invisible; on `sp500_2023.toml`, which declares `benchmark = ""` so the
optimiser cannot hold SPY, the key became "benchmark:None" and matched nothing.

**And the two blocks then behave differently, which is the whole point.** A mislabelled ROLLING
block is loud: `summary_table` subscripts the row it looked up and dies with a TypeError before
`write_json` is reached, so no artifact is produced. A mislabelled WINDOW block is silent:
`window_table` is None-tolerant on purpose -- a strategy legitimately missing from a period prints
`--` -- so the run completes, prints `--` in both benchmark columns, and writes a file whose
benchmark comparison is against nothing. Same one-line mistake, fatal in one block and cosmetic in
the other. That asymmetry is what these assertions are for, and it is what they were
mutation-checked against (2026-09-06: pointing the window block's label at `u.benchmark` wrote a
32 KiB file and failed the first two tests below by name).

Two of the three tests here cannot be reached by `main` at all in their *original* form -- see their
docstrings. They are kept for the read-back value above and because the mislabel trips them too,
not because they guard a live path.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pytest

RESULTS = Path(__file__).resolve().parents[1] / "results"
FILES = sorted(RESULTS.glob("*.json"))


def _kind(path: Path) -> str:
    return json.loads(path.read_text()).get("kind", "backtest")


# SPLIT BY `kind`, NOT BY FILENAME. `delisted.py --stress` writes its bound next to the result it
# came from, and a stress file has no `periods` -- so parametrising every test over `*.json` makes
# `_blocks` return an empty list for it and the loops below pass without executing once. A vacuous
# pass is the exact failure this module's docstring is about, so the discriminator is a field in
# the file and a file with neither shape is a hard error rather than a skip.
#
# `pit_backtest` is the third kind and arrived exactly the way the guard below was written for: as
# four new files in `pipeline/results/` that `test_every_committed_result_has_a_shape_this_file_knows_about`
# failed on by name. It carries `benchmark` and `periods` at the TOP LEVEL rather than under
# `rolling[0]`, because a point-in-time run has one kind of block and nesting it would be a nesting
# of one. Every assertion below applies to it unchanged once `_blocks` knows the shape -- which is
# the reason to teach this file the kind rather than to add a second file for it.
BACKTESTS = [p.name for p in FILES if _kind(p) == "backtest"]
PIT = [p.name for p in FILES if _kind(p) == "pit_backtest"]
STRESS = [p.name for p in FILES if _kind(p) == "stress_bound"]
OTHER = [p.name for p in FILES if _kind(p) not in ("backtest", "pit_backtest", "stress_bound")]


def test_every_committed_result_has_a_shape_this_file_knows_about():
    """The guard on the split above. A new artifact kind dropped into `pipeline/results/` would
    otherwise be tested by nothing at all, silently, because it matches neither list."""
    assert not OTHER, f"unrecognised `kind` in {OTHER} -- add it to this file or it is untested"
    assert BACKTESTS, "no committed backtest results -- run `python -u pipeline/backtest.py`"


@pytest.fixture(scope="module", params=(BACKTESTS + PIT) or ["none"])
def result(request):
    if request.param == "none":
        pytest.skip("no committed results -- run `python -u pipeline/backtest.py` first")
    return json.loads((RESULTS / request.param).read_text())


@pytest.fixture(scope="module", params=STRESS or ["none"])
def stress(request):
    if request.param == "none":
        pytest.skip("no committed stress bounds -- run `pipeline/delisted.py --stress`")
    return json.loads((RESULTS / request.param).read_text())


def _blocks(result: dict) -> list[tuple[str, dict]]:
    """Every part of the file that names a benchmark and carries periods to measure it over.

    Shape-driven rather than kind-driven, and the last clause is what makes a `pit_backtest` -- whose
    single block IS the document -- yield one block instead of none. A kind-driven version would
    return an empty list for any future document that also carries its periods at the top level, and
    an empty list is a vacuous pass in all three tests below.
    """
    out: list[tuple[str, dict]] = []
    if "window" in result:
        out.append(("window", result["window"]))
    for i, b in enumerate(result.get("rolling", [])):
        out.append((f"rolling[{i}]", b))
    if "periods" in result:
        out.append(("periods", result))
    return out


def _held_out(result: dict) -> str | None:
    """The benchmark this run declares priced but not investable, or None if it let the optimiser
    hold it. Two shapes: `backtest.py` puts the flag under `universe`, `pit.py` at the top level,
    because a point-in-time run has no single universe to describe."""
    block = result.get("universe", result)
    return None if block.get("benchmark_investable", True) else block["benchmark"]


def _pid(period: dict) -> str:
    """The period's identity for a failure message. `period` and not `test.start` -- a test block
    carries `end`, `bars` and `years`, so a message built from `test["start"]` names every period
    `None`, which is how the first version of this file read."""
    return period.get("period", "?")


def test_every_block_names_a_benchmark_its_own_periods_actually_measured(result):
    """The join key resolves, in every period of every block.

    Asserted per PERIOD rather than "somewhere in the block": a benchmark that resolves in the
    first period and not the fourth is a strategy that stopped being priced part way, which is a
    different failure and equally silent -- the win count would just be smaller.
    """
    for name, block in _blocks(result):
        bm = block["benchmark"]
        assert bm, f"{name}: benchmark is {bm!r}, so no printer can find its row"
        key = f"benchmark:{bm}"
        for p in block["periods"]:
            labels = [s["strategy"] for s in p["strategies"]]
            assert key in labels, (
                f"{name} period {_pid(p)}: no {key!r} row among {labels}. The block's `benchmark` "
                "field is the lookup key every printer builds, so this is a comparison against "
                "nothing, not a missing label."
            )


def test_the_benchmark_appears_exactly_once_per_period(result):
    """One row, not two.

    THE DUPLICATE ITSELF IS UNREACHABLE FROM `main`, and saying so is the point of this docstring.
    `evaluate` emits the benchmark row when the benchmark is among the candidates and adds it
    separately when it is held out; gating the second on `investable is not None` rather than on
    absence from the candidate set appended a second identical row. But `main` only builds an
    `investable` list *when* the benchmark is held out, so the two conditions never disagree on any
    run this CLI can perform -- the bug needs an explicit list containing the benchmark, which is
    why `test_holding_nothing_out_is_the_same_run_as_not_holding_out_at_all` is synthetic and the real
    guard. What this adds is the mislabel above, which it catches as 0 rows rather than 2, and the
    fact that it reads the committed files at all.
    """
    for name, block in _blocks(result):
        key = f"benchmark:{block['benchmark']}"
        for p in block["periods"]:
            n = sum(1 for s in p["strategies"] if s["strategy"] == key)
            assert n == 1, f"{name} period {_pid(p)}: {n} {key!r} rows"


def test_a_held_out_benchmark_is_priced_and_not_investable(result):
    """`benchmark_investable: false` is a claim about two things at once -- the benchmark has a
    measured row (priced) and no strategy holds it (not investable). Both, or the held-out run is
    not the thing it says it is.

    Also unreachable from `main` in the ordinary way: holding the benchmark out removes it from
    `est_s`, so no weight vector can contain it and no live path can violate this. It is a read-back
    check on committed evidence -- a file generated before the held-out plumbing existed, or edited.

    Checked against `top_holdings`, which is the top `--top` positions and NOT the whole weight
    vector, so this can only catch the benchmark held at a size that reaches that list. That is a
    limit of the artifact rather than of the test, and it is the right way round: an index fund
    among its own constituents is bought by the minimum-variance solve at a LARGE weight, because
    lower variance is exactly what it has. A 0.2% leak is not the failure mode.
    """
    bm = _held_out(result)
    if bm is None:
        pytest.skip("this run let the optimiser hold its benchmark")
    assert bm, "a run declaring its benchmark not investable has to name it"
    checked = 0
    for name, block in _blocks(result):
        for p in block["periods"]:
            for s in p["strategies"]:
                if s["strategy"] == f"benchmark:{bm}":
                    continue
                assert bm not in (s["top_holdings"] or {}), (
                    f"{name} period {_pid(p)}: {s['strategy']} holds {bm}, which this run "
                    "declares not investable"
                )
                checked += 1
    assert checked > 0, "no strategy row was examined, so this checked nothing"


def test_a_stress_bound_names_a_result_that_exists_and_quotes_its_benchmark_correctly(stress):
    """A companion file has one way to be wrong that nothing else can see: it can be STALE.

    `delisted.py --stress` reads a result and writes its bound beside it, so the two are separate
    files with no shared timestamp -- re-run the backtest and the bound sitting next to it now
    describes the previous run. Every number in it is still individually plausible, which is why
    this is checked by recomputing the one quantity both files contain rather than by comparing a
    field to itself: the benchmark's return per unit of risk, from the named result's own periods.

    Recompute-to-recompute at the file's own precision (4 dp), not against a rounded field at
    1e-9 -- see this repo's third false-comparison trap. `years` is DERIVED FROM THE SPAN DATES
    rather than read off `span.years`, which is rounded to 3 dp for transport: the first version
    of this test read the field and failed on correct code by one unit in the fourth decimal,
    which is that same trap one level down.
    """
    named = RESULTS / stress["result"]
    assert named.exists(), f"the bound names {stress['result']}, which is not committed"
    # The bound is always taken over the NON-NESTED block: `rolling[0]` in `backtest.py`'s shape,
    # the document itself in `pit.py`'s. Not `_blocks(...)[0]`, which is the `window` block on a file
    # that has one -- and a window block's periods are nested, so recomputing over them would
    # compare the bound against a span it was never built from.
    doc = json.loads(named.read_text())
    block = doc["rolling"][0] if doc.get("rolling") else doc
    periods = block["periods"]
    label = f"benchmark:{block['benchmark']}"
    rows = [next(s for s in p["strategies"] if s["strategy"] == label) for p in periods]
    growth = 1.0
    for r in rows:
        growth *= 1.0 + r["realized_monthly"]["ret"]
    risk = sum(r["realized_monthly"]["vol"] for r in rows) / len(rows)
    span = stress["span"]
    years = (date.fromisoformat(span["end"]) - date.fromisoformat(span["start"])).days / 365.25
    ratio = (growth ** (1.0 / years) - 1.0) / risk
    assert round(ratio, 4) == stress["optimised"][next(iter(stress["optimised"]))][
        "benchmark_return_per_unit_of_risk"], (
        f"{stress['result']}'s benchmark computes to {ratio:.4f} and the bound beside it says "
        "otherwise, so one of the two files is from an older run"
    )


def test_a_bound_over_a_point_in_time_run_bounds_that_runs_own_missing_names(stress):
    """The set bounded has to come off the run, not off the membership file.

    `sp500_pit.toml` has an `unpriceable` list, and passing it is the obvious thing to do and wrong
    in two directions at once: it omits the constituents whose ticker now means another company
    (stripped before `load_panel`, so they appear in no `dropped` reason), and it includes the
    twenty-three the second vendor serves -- which are missing from a baseline run and present in a
    restored one, so one literal cannot be right for both. 67 names against the run's own 99 on the
    restored runs and 102 on the baseline: a name the second vendor supplies from 2015 is still
    absent from the window that needed 2011, so restoring 23 names removes 3 from the union.

    Nothing else can see this. Every number in a bound built from the wrong set is plausible, the
    span is right, the benchmark ratio above still reconciles, and the bound is simply too narrow.
    So it is checked by rebuilding the union from the named result's own periods.
    """
    doc = json.loads((RESULTS / stress["result"]).read_text())
    if doc.get("kind") != "pit_backtest":
        pytest.skip("only a point-in-time run records its missing constituents per period")
    union = sorted({s for p in doc["periods"] for s in p["membership"]["unpriced_constituents"]})
    assert stress["unpriceable"] == union, (
        f"the bound beside {stress['result']} covers {len(stress['unpriceable'])} names and that "
        f"run's own periods are missing {len(union)}; symmetric difference "
        f"{sorted(set(union) ^ set(stress['unpriceable']))}"
    )
    assert stress["n_unpriceable"] == len(union)
